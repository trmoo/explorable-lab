import { 묶음, 확인, 참 } from './harness.mjs';
import {
  빈설계, 설계점검, 설계완료, 프롬프트만들기, 프롬프트요소, 눈목록, 범위점검, 링크검사, 고치기문장,
} from '../src/engine/design.js';

const 좋은설계 = () => ({
  ...빈설계(),
  과목: '수학 · 확률', 주제: '생일 문제', 대상: '고등학생',
  아하: '사람 수가 23명만 되어도 확률이 절반을 넘는다.',
  예측: '몇 명이 모이면 확률이 50%를 넘을까?',
  변수: [{ 이름: '사람 수', 최소: '2', 최대: '60', 기본: '10', 단위: '명' }],
  화면: '왼쪽에 달력 점, 오른쪽에 확률 꺾은선 그래프',
  결과: '확률 숫자와 그래프 위 점이 바뀐다',
});

묶음('설계 점검');
{
  참('빈 설계는 완료가 아니다', !설계완료(빈설계()));
  참('잘 쓴 설계는 완료', 설계완료(좋은설계()));
  const 점 = 설계점검(좋은설계());
  참('권장 항목 — 아하 문장에 변수 이름(사람 수)이 있다', 점.find((c) => c.id === '이어짐').ok);
  참('권장 항목은 완료를 막지 않는다', 설계완료({ ...좋은설계(), 아하: '생일이 같은 사람이 생각보다 훨씬 쉽게 생긴다.' }));

  const 넷 = { ...좋은설계(), 변수: Array.from({ length: 4 }, (_, i) => ({ 이름: `변수${i}`, 최소: '0', 최대: '1', 기본: '0', 단위: '' })) };
  참('변수 4개는 너무 많다', !설계완료(넷));
  참('너무 많을 때 이유를 말해 준다', 설계점검(넷).find((c) => c.id === '변수개수').글.includes('너무 많'));
  참('예측 질문은 묻는 꼴이어야 한다', !설계완료({ ...좋은설계(), 예측: '사람 수가 늘면 확률이 오른다' }));
  참('「까」로 끝나는 질문도 받는다', 설계완료({ ...좋은설계(), 예측: '몇 명이면 절반을 넘을까' }));
  참('이름 없는 빈 변수 줄은 세지 않는다', 설계완료({ ...좋은설계(), 변수: [...좋은설계().변수, { 이름: '', 최소: '', 최대: '', 기본: '', 단위: '' }] }));
}

묶음('범위 점검 (경계값)');
{
  확인('바른 범위', 범위점검({ 최소: '0', 최대: '10', 기본: '5' }), '');
  참('숫자가 아니면 막는다', !!범위점검({ 최소: '가', 최대: '10', 기본: '5' }));
  참('최소 ≥ 최대 를 막는다', !!범위점검({ 최소: '10', 최대: '10', 기본: '10' }));
  참('처음 값이 범위 밖이면 막는다', !!범위점검({ 최소: '0', 최대: '10', 기본: '11' }));
  확인('소수도 받는다', 범위점검({ 최소: '0.01', 최대: '1', 기본: '0.1' }), '');
  확인('처음 값이 끝값이어도 된다', 범위점검({ 최소: '0', 최대: '1', 기본: '1' }), '');
  참('빈 칸은 0 이 아니다 (Number("") === 0 함정)', !!범위점검({ 최소: '', 최대: '10', 기본: '5' }));
}

묶음('프롬프트 조립');
{
  const d = 좋은설계();
  const 글 = 프롬프트만들기(d);
  for (const 조각 of ['HTML 파일 하나', '생일 문제', '고등학생', '[화면 구성]', '[조작 요소]', '[피드백]', '[학습 목표]', '사람 수 슬라이더 (2명~60명, 처음 값 10명)']) {
    참(`프롬프트에 「${조각}」이 들어간다`, 글.includes(조각));
  }
  참('예측 먼저(기본 켜짐)', 글.includes('예측을 고르게'));
  참('예측 먼저를 끄면 빠진다', !프롬프트만들기({ ...d, 예측먼저: false }).includes('예측을 고르게'));
  참('정답을 먼저 알려 주지 말라는 줄', 글.includes('정답을 먼저 알려 주지 말고'));
  참('눈을 안 켜면 [꼼꼼하게] 가 없다', !글.includes('[꼼꼼하게]'));
  const 켬 = { ...d, 눈: { 초기화: true, 시드: true } };
  const 켠글 = 프롬프트만들기(켬);
  참('눈을 켜면 [꼼꼼하게] 가 생긴다', 켠글.includes('[꼼꼼하게]'));
  참('켠 눈의 줄이 들어간다', 켠글.includes(눈목록.find((e) => e.id === '시드').줄));
  참('안 켠 눈의 줄은 없다', !켠글.includes(눈목록.find((e) => e.id === '색').줄));
  확인('보통판은 눈을 무시한다', 프롬프트만들기(켬, { 눈켜기: false }), 글);
  참('프로그래머판이 보통판보다 길다', 켠글.length > 글.length);
  참('빈 설계도 오류 없이 자리 표시를 넣는다', 프롬프트만들기(빈설계()).includes('(주제를 적어요)'));
  참('6요소 모두 충족', 프롬프트요소(d).every((x) => x.ok));
  확인('6요소 개수', 프롬프트요소(d).length, 6);
  참('빈 설계는 6요소가 비어 있다', 프롬프트요소(빈설계()).filter((x) => x.ok).length <= 2);
}

묶음('프로그래머의 눈 목록');
{
  확인('여덟 가지', 눈목록.length, 8);
  참('id 가 겹치지 않는다', new Set(눈목록.map((e) => e.id)).size === 눈목록.length);
  참('모두 이유와 프롬프트 줄이 있다', 눈목록.every((e) => e.왜.length > 10 && e.줄.length > 10));
  참('고치기 문장은 모두 「한 군데만」 고치게 하거나 무엇을 고칠지 콕 집는다', 고치기문장.length >= 6);
}

묶음('공유 링크 검사');
{
  참('gemini.google.com/share', 링크검사('https://gemini.google.com/share/abc123').ok);
  참('g.co/gemini/share', 링크검사('https://g.co/gemini/share/xyz').ok);
  참('앞뒤 빈칸은 걷어 낸다', 링크검사('  https://gemini.google.com/share/abc  ').ok);
  참('내 대화창 주소(/app)는 막는다', !링크검사('https://gemini.google.com/app/123').ok);
  참('빈 칸은 아니다', !링크검사('').ok);
  참('주소가 아닌 글은 막는다', !링크검사('제미나이 링크').ok);
  참('http 는 막는다', !링크검사('http://gemini.google.com/share/abc').ok);
  참('javascript: 주소는 막는다', !링크검사('javascript:alert(1)').ok);
  const 다른 = 링크검사('https://example.com/x');
  참('다른 https 주소는 받되 경고한다', 다른.ok && 다른.경고);
}

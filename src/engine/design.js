export const 글자수 = (글) => String(글 ?? '').replace(/\s/g, '').length;

// 이름이 적힌 변수만
export const 쓴변수 = (설계) => (설계?.변수 || []).filter((v) => String(v.이름 || '').trim());

function 수인가(값) {
  return String(값 ?? '').trim() !== '' && Number.isFinite(Number(값));
}

// 변수 하나의 범위가 말이 되는가
export function 범위점검(v) {
  if (!수인가(v.최소) || !수인가(v.최대)) return '최솟값·최댓값을 숫자로 적어요';
  const lo = Number(v.최소), hi = Number(v.최대);
  if (lo >= hi) return '최솟값이 최댓값보다 작아야 해요';
  if (!수인가(v.기본)) return '처음 값(기본값)을 숫자로 적어요';
  const d = Number(v.기본);
  if (d < lo || d > hi) return '처음 값이 범위 밖이에요';
  return '';
}

// 설계 점검 — 필수(꼭)와 권장(있으면 좋음)을 나눈다.
//   돌려주는 것: [{ id, 꼭, ok, 글, 고칠 }]
export function 설계점검(설계) {
  const d = 설계 || 빈설계();
  const 변수 = 쓴변수(d);
  const 결과 = [];
  const 넣기 = (id, 꼭, ok, 글, 고칠) => 결과.push({ id, 꼭, ok: !!ok, 글, 고칠: ok ? '' : 고칠 });

  넣기('주제', true, 글자수(d.주제) >= 2, '주제(어떤 개념인가)', '어떤 개념을 보여 줄지 적어요');
  넣기('아하', true, 글자수(d.아하) >= 10, '「아하!」 한 문장', '학생이 깨닫기를 바라는 것을 한 문장(10자 이상)으로');
  넣기('예측', true, 글자수(d.예측) >= 8 && /[?？까]/.test(d.예측), '먼저 던질 예측 질문', '「~하면 어떻게 될까?」처럼 묻는 문장으로');
  넣기('변수개수', true, 변수.length >= 1 && 변수.length <= 3,
    변수.length > 3 ? '바꿀 변수 1~3개 (지금 너무 많아요)' : '바꿀 변수 1~3개',
    변수.length > 3 ? '변수가 많으면 무엇 때문에 바뀌었는지 알 수 없어요. 3개 이하로' : '바꿔 볼 값을 하나 이상 적어요');
  const 범위문제 = 변수.map((v) => [v.이름, 범위점검(v)]).filter(([, m]) => m);
  넣기('범위', true, 변수.length > 0 && 범위문제.length === 0, '변수마다 범위와 처음 값',
    범위문제.length ? `「${범위문제[0][0]}」: ${범위문제[0][1]}` : '변수를 먼저 적어요');
  넣기('화면', true, 글자수(d.화면) >= 10, '화면에 무엇이 보이나', '화면 구성을 10자 이상으로');
  넣기('결과', true, 글자수(d.결과) >= 10, '값을 바꾸면 무엇이 변하나', '바뀌는 것을 10자 이상으로');
  넣기('대상', true, 글자수(d.대상) >= 2, '누가 쓰나(대상)', '대상을 골라요');

  // 권장 — 아하 문장에 변수 이름이 들어가면 「무엇을 바꾸면 무엇을 깨닫는지」가 분명해진다
  const 이어짐 = 변수.some((v) => String(d.아하 || '').includes(String(v.이름).trim()));
  넣기('이어짐', false, 이어짐, '(권장) 아하 문장에 변수 이름이 들어 있다', '아하 문장에 바꿀 변수를 넣으면 더 분명해져요');
  return 결과;
}

export function 설계완료(설계) {
  return 설계점검(설계).filter((c) => c.꼭).every((c) => c.ok);
}


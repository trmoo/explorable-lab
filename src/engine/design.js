export function 변수줄(v) {
  const 단 = String(v.단위 || '').trim();
  const 범위 = (수인가(v.최소) && 수인가(v.최대)) ? ` (${v.최소}${단}~${v.최대}${단}` + (수인가(v.기본) ? `, 처음 값 ${v.기본}${단})` : ')') : '';
  return `- ${String(v.이름).trim()} 슬라이더${범위}`;
}

